  function t(key, vars) {
    const d = dicts[lang] || dicts.zh;
    let s = d[key] !== undefined ? d[key] : (dicts.zh[key] !== undefined ? dicts.zh[key] : key);
    if (vars) {
      for (const k of Object.keys(vars)) {
        s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), String(vars[k]));
      }
    }
    return s;
  }

